def select_file():
    dialog=next(w for w in QtWidgets.QApplication.topLevelWidgets() if isinstance(w,QtWidgets.QFileDialog) and w.isVisible())
    dialog.setDirectory(str(out/'project'))
    edit=dialog.findChild(QtWidgets.QLineEdit,'fileNameEdit')
    click(edit,edit.width()//2,edit.height()//2)
    QtTest.QTest.keyClick(edit,QtCore.Qt.Key_A,QtCore.Qt.ControlModifier)
    QtTest.QTest.keyClicks(edit,'robot4.FCStd',delay=85)
    QtTest.QTest.qWait(500)
    button=next(b for b in dialog.findChildren(QtWidgets.QPushButton) if b.text().replace('&','')=='Open')
    click(button,button.width()//2,button.height()//2)
QtCore.QTimer.singleShot(1000,select_file)
